a = 5

b = 6

# equal to operator
print("a == b:", a==b)

# not equal to operator
print("a != b:", a!=b)

# greater than operator
print("a > b:", a>b)

# less than operator
print("a < b:", a<b)

# greater than or equal to operator
print("a >= b:", a>=b)

# less than or equal to operator 
print("a <= b:", a<=b)
