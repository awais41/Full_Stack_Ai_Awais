# Question 11:
# Age in Months and Days
# Input your age in years. Calculate and print age in:
# Months
# Days (approximate)

age_years = float(input("Enter your age in years: "))

age_in_months = age_years * 12
age_in_days = age_years * 365

print("Age in months:", age_in_months)
print("Age in days (approximate):", age_in_days)